void pc1401_state::pc1401_mem(address_map &map)
{
	map(0x0000, 0x1fff).rom();
	map(0x3800, 0x47ff).ram();
	map(0x6000, 0x67ff).rw(FUNC(pc1401_state::lcd_read), FUNC(pc1401_state::lcd_write)).mirror(0x1000);
	map(0x8000, 0xffff).rom();
}

