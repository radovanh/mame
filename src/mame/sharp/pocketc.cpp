void pc1251_state::pc1260_mem(address_map &map)
{
	map(0x0000, 0x1fff).rom();
	map(0x2000, 0x20ff).rw(FUNC(pc1251_state::lcd_read), FUNC(pc1251_state::lcd_write));
	// Second display line ("Anzeige-Speicher 2") -- PC-1260/1261 only.
	// Previously left unmapped entirely, which silently swallowed anything
	// the ROM wrote here (e.g. a calculation result landing on the second
	// line) -- user-confirmed this was the root cause of the "1+1 does
	// nothing" ERROR 1 symptom. Backed by lcd2_read()/lcd2_write() (m_reg2),
	// same pattern as the first line's own 0x2000-0x20ff window above.
	map(0x2800, 0x28ff).rw(FUNC(pc1251_state::lcd2_read), FUNC(pc1251_state::lcd2_write));
	map(0x5800, 0x67ff).ram(); // 4KB RAM
	map(0x8000, 0xffff).rom();
}

void pc1251_state::pc1261_mem(address_map &map)
{
	map(0x0000, 0x1fff).rom();
	map(0x2000, 0x20ff).rw(FUNC(pc1251_state::lcd_read), FUNC(pc1251_state::lcd_write));
	// See pc1260_mem() above.
	map(0x2800, 0x28ff).rw(FUNC(pc1251_state::lcd2_read), FUNC(pc1251_state::lcd2_write));
	map(0x4000, 0x67ff).ram(); // 10KB RAM
	map(0x8000, 0xffff).rom();
}

